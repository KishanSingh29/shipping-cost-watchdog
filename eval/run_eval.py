
"""Evaluate predictions against human labels.

Blank labels are intentionally not scored. expected_flagged represents
numeric anomaly detection independently of note-based justification.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


REQUIRED = {
    "case_id",
    "route",
    "week_of",
    "expected_flagged",
    "expected_verdict",
    "expected_note_id",
}

VALID_VERDICTS = {"justified", "unexplained", "not_flagged"}
VALID_FLAGS = {"", "0", "1"}


def normalize_note_id(value: object) -> str:
    """Convert missing note IDs to empty strings."""
    if pd.isna(value):
        return ""
    normalized = str(value).strip()
    if normalized.lower() in {"nan", "none", "null"}:
        return ""
    return normalized


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Evaluate shipping cost watchdog predictions."
    )
    parser.add_argument(
        "--labels",
        default="eval/labeled_cases.csv",
        help="CSV containing human-labelled evaluation cases.",
    )
    parser.add_argument(
        "--predictions",
        default="outputs/watchlist.csv",
        help="CSV generated by the watchdog pipeline.",
    )
    parser.add_argument(
        "--out",
        default="outputs/eval_report.md",
        help="Markdown report output path.",
    )
    args = parser.parse_args()

    labels_path = Path(args.labels)
    predictions_path = Path(args.predictions)
    output_path = Path(args.out)

    if not labels_path.exists():
        raise SystemExit(f"Label file not found: {labels_path}")
    if not predictions_path.exists():
        raise SystemExit(f"Predictions not found: {predictions_path}")

    labels = pd.read_csv(labels_path, dtype=str).fillna("")
    predictions = pd.read_csv(
        predictions_path, dtype=str, keep_default_na=False
    ).fillna("")

    missing_columns = REQUIRED - set(labels.columns)
    if missing_columns:
        raise SystemExit(
            f"Label file missing columns: {sorted(missing_columns)}"
        )

    prediction_columns = {
        "route", "week_of", "flagged", "matched_note_id"
    }
    missing_columns = prediction_columns - set(predictions.columns)
    if missing_columns:
        raise SystemExit(
            f"Prediction file missing columns: {sorted(missing_columns)}"
        )

    # Normalize keys and labels before validating or merging.
    for frame in (labels, predictions):
        frame["route"] = frame["route"].astype(str).str.strip()
        frame["week_of"] = pd.to_datetime(
            frame["week_of"], errors="coerce"
        ).dt.strftime("%Y-%m-%d").fillna("")

    for column in (
        "expected_flagged",
        "expected_verdict",
        "expected_note_id",
    ):
        labels[column] = labels[column].map(normalize_note_id)

    predictions["flagged"] = predictions["flagged"].str.strip()
    predictions["matched_note_id"] = predictions[
        "matched_note_id"
    ].map(normalize_note_id)

    invalid_flags = set(labels["expected_flagged"]) - VALID_FLAGS
    if invalid_flags:
        raise SystemExit(
            f"Invalid expected_flagged values: {sorted(invalid_flags)}"
        )

    invalid_verdicts = (
        set(labels["expected_verdict"]) - VALID_VERDICTS - {""}
    )
    if invalid_verdicts:
        raise SystemExit(
            f"Invalid expected_verdict values: {sorted(invalid_verdicts)}. "
            f"Use: {sorted(VALID_VERDICTS)}"
        )

    # A verdict must not be scored without its numeric-anomaly label,
    # or vice versa. Blank labels remain excluded.
    labelled = labels[
        labels["expected_flagged"].isin({"0", "1"})
        & labels["expected_verdict"].isin(VALID_VERDICTS)
    ].copy()

    report = [
        "# Evaluation report",
        "",
        f"Cases in template: {len(labels)}",
        f"Cases scored: {len(labelled)}",
        f"Cases excluded due to incomplete labels: {len(labels) - len(labelled)}",
        "",
        "## Metric definitions",
        "",
        "- **Flag accuracy:** numeric anomaly detection accuracy. "
        "Both `Yes` and `No (justified)` mean an anomaly was detected.",
        "- **Verdict accuracy:** accuracy of `justified`, `unexplained`, "
        "or `not_flagged` verdicts.",
        "- **Note ID accuracy:** exact match of the expected and predicted "
        "supporting note IDs. Two blank IDs count as a match.",
        "",
    ]

    if labelled.empty:
        report.extend([
            "No metrics computed because no cases have complete labels.",
            "Inspect shipment data and context notes before supplying "
            "ground-truth labels.",
            "",
        ])
    else:
        duplicate_keys = predictions.duplicated(
            subset=["route", "week_of"], keep=False
        )
        if duplicate_keys.any():
            duplicates = predictions.loc[
                duplicate_keys, ["route", "week_of"]
            ].drop_duplicates()
            raise SystemExit(
                "Duplicate route-week keys in predictions:\n"
                + duplicates.to_string(index=False)
            )

        merged = labelled.merge(
            predictions,
            on=["route", "week_of"],
            how="left",
            indicator=True,
            validate="many_to_one",
            suffixes=("_expected", "_actual"),
        )

        emitted = merged["_merge"].eq("both")
        actual_status = merged["flagged"].fillna("").str.strip()

        # Watchlist contains only numeric anomaly candidates.
        actual_flag = emitted
        expected_flag = merged["expected_flagged"].eq("1")

        verdict_actual = pd.Series(
            "not_flagged", index=merged.index, dtype="object"
        )
        verdict_actual.loc[
            emitted & actual_status.eq("Yes")
        ] = "unexplained"
        verdict_actual.loc[
            emitted & actual_status.eq("No (justified)")
        ] = "justified"

        # Unknown statuses should not silently count as correct.
        unknown_status = emitted & ~actual_status.isin(
            {"Yes", "No (justified)"}
        )
        if unknown_status.any():
            raise SystemExit(
                "Unexpected flagged values in predictions: "
                f"{sorted(actual_status[unknown_status].unique())}"
            )

        expected_verdict = merged["expected_verdict"]

        note_actual = merged["matched_note_id"].map(normalize_note_id)
        note_expected = merged["expected_note_id"].map(normalize_note_id)

        flag_accuracy = (actual_flag == expected_flag).mean()
        verdict_accuracy = (
            verdict_actual == expected_verdict
        ).mean()
        note_accuracy = (note_actual == note_expected).mean()

        report.extend([
            "## Metrics",
            "",
            f"- Flag accuracy: **{flag_accuracy:.3f}**",
            f"- Verdict accuracy: **{verdict_accuracy:.3f}**",
            f"- Note ID accuracy: **{note_accuracy:.3f}**",
            "",
            "## Labelled case results",
            "",
            "| Case | Route | Week | Expected flag | Actual flag | "
            "Expected verdict | Actual verdict | Expected note | Actual note |",
            "|---|---|---|---:|---:|---|---|---|---|",
        ])

        for idx, row in merged.iterrows():
            expected_note = note_expected.loc[idx] or "(blank)"
            actual_note = note_actual.loc[idx] or "(blank)"
            actual_flag_value = "1" if emitted.loc[idx] else "0"

            report.append(
                f"| {row['case_id']} | {row['route']} | {row['week_of']} | "
                f"{row['expected_flagged']} | {actual_flag_value} | "
                f"{expected_verdict.loc[idx]} | {verdict_actual.loc[idx]} | "
                f"{expected_note} | {actual_note} |"
            )

        report.extend([
            "",
            "## Important limitations",
            "",
            "- Metrics are trustworthy only when labels are independently "
            "verified against source data and context notes.",
            "- Cases with the same route and week share the same prediction.",
            "- Missing route-week data is not automatically evidence of a "
            "negative case.",
            "- A supporting note is evidence of a possible cause, not proof "
            "that it explains the entire cost increase.",
            "",
        ])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        "\n".join(report) + "\n", encoding="utf-8"
    )

    print("\n".join(report))
    print(f"\nReport saved to: {output_path}")


if __name__ == "__main__":
    main()
